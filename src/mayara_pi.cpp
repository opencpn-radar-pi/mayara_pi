// Keep the persisted Signal K access state in step with the client, and raise
// the approval dialog the first time a control write is refused.
void mayara_pi::SyncAccessConfig() {
  if (!m_client) return;
  bool dirty = false;
  const std::string token = m_client->AuthToken();
  if (token != m_sk_token) {
    m_sk_token = token;
    m_sk_token_server = m_client->AuthTokenServer();
    dirty = true;
  }
  const std::string href = m_client->PendingHref();
  if (href != m_sk_pending_href) {
    m_sk_pending_href = href;
    m_sk_pending_server = m_client->PendingServer();
    dirty = true;
  }
  if (dirty) {
    wxFileConfig* cfg = GetOCPNConfigObject();
    if (cfg) {
      cfg->SetPath(kConfigGroup);
      cfg->Write("SignalKToken", wxString::FromUTF8(m_sk_token.c_str()));
      cfg->Write("SignalKTokenServer",
                 wxString::FromUTF8(m_sk_token_server.c_str()));
      cfg->Write("SignalKPendingHref",
                 wxString::FromUTF8(m_sk_pending_href.c_str()));
      cfg->Write("SignalKPendingServer",
                 wxString::FromUTF8(m_sk_pending_server.c_str()));
      cfg->Flush();
    }
  }

  const MayaraClient::AuthState state = m_client->Auth();
  // The radar silently ignoring the transmit button is the worst outcome, so
  // explain it as soon as the server refuses a write.
  if (!m_access_dialog && !m_access_dismissed &&
      (state == MayaraClient::AuthState::kNeeded ||
       state == MayaraClient::AuthState::kPending))
    ShowAccessDialog();
  UpdateAccessDialog();
}

// Shown when the Signal K server refuses radar control: explains the approval
// step and drives Signal K's access-request flow.
void mayara_pi::ShowAccessDialog() {
  if (m_access_dialog) return;
  auto* dlg = new wxDialog(m_parent_window, wxID_ANY,
                           _("Mayara - permission needed"), wxDefaultPosition,
                           wxDefaultSize, wxDEFAULT_DIALOG_STYLE);
  m_access_dialog = dlg;
  auto* top = new wxBoxSizer(wxVERTICAL);
  auto* intro = new wxStaticText(
      dlg, wxID_ANY,
      _("Your Signal K server allows this plugin to read radar data, but not "
        "to control the radar, so buttons like Transmit do nothing.\n\n"
        "Ask the server for permission below, then approve the request in the "
        "Signal K web interface under Security -> Access Requests. The "
        "permission is remembered, so this is only needed once."));
  intro->Wrap(intro->FromDIP(420));
  top->Add(intro, 0, wxALL, 12);

  m_access_status = new wxStaticText(dlg, wxID_ANY, wxEmptyString);
  top->Add(m_access_status, 0, wxLEFT | wxRIGHT | wxBOTTOM, 12);

  auto* btns = new wxBoxSizer(wxHORIZONTAL);
  m_access_button = new wxButton(dlg, wxID_ANY, _("Ask for permission"));
  auto* later = new wxButton(dlg, wxID_ANY, _("Not now"));
  btns->AddStretchSpacer();
  btns->Add(later, 0, wxRIGHT, 8);
  btns->Add(m_access_button, 0);
  top->Add(btns, 0, wxEXPAND | wxALL, 12);
  dlg->SetSizerAndFit(top);

  m_access_button->Bind(wxEVT_BUTTON, [this](wxCommandEvent&) {
    if (m_client) m_client->RequestAccess();
    UpdateAccessDialog();
  });
  auto close = [this](wxEvent&) {
    m_access_dismissed = true;
    m_access_status = nullptr;
    m_access_button = nullptr;
    if (m_access_dialog) {
      m_access_dialog->Destroy();
      m_access_dialog = nullptr;
    }
  };
  later->Bind(wxEVT_BUTTON, close);
  dlg->Bind(wxEVT_CLOSE_WINDOW, close);
  UpdateAccessDialog();
  dlg->Show();
}

void mayara_pi::UpdateAccessDialog() {
  if (!m_access_dialog || !m_client || !m_access_status) return;
  const MayaraClient::AuthState state = m_client->Auth();
  const wxString detail = wxString::FromUTF8(m_client->AuthMessage().c_str());
  wxString line;
  bool can_ask = true;
  switch (state) {
    case MayaraClient::AuthState::kRequesting:
      line = _("Asking the server...");
      can_ask = false;
      break;
    case MayaraClient::AuthState::kPending:
      line = _("Waiting - approve \"Mayara radar plugin for OpenCPN\" in "
               "Signal K under Security -> Access Requests.");
      can_ask = false;
      break;
    case MayaraClient::AuthState::kApproved:
      line = _("Approved. Radar control works now.");
      can_ask = false;
      break;
    case MayaraClient::AuthState::kDenied:
      line = _("The request was refused. You can ask again.");
      break;
    case MayaraClient::AuthState::kUnavailable:
      line = _("This server does not hand out permissions this way; it has to "
               "be granted in its own configuration.");
      can_ask = false;
      break;
    default:
      line = _("No permission yet.");
      break;
  }
  if (!detail.IsEmpty()) line += "\n(" + detail + ")";
  if (line == m_access_last_line) return;  // called once a second; don't churn
  m_access_last_line = line;
  m_access_status->SetLabel(line);
  m_access_status->Wrap(m_access_status->FromDIP(420));
  if (m_access_button) m_access_button->Enable(can_ask);
  m_access_dialog->Layout();
  m_access_dialog->Fit();
  // Approval is the end of the story; let the user get on with it.
  if (state == MayaraClient::AuthState::kApproved) m_access_dismissed = true;
}

// The client tries our own server ahead of mDNS, but only while we actually
// have one; otherwise it must fall back to the network as before.
// True when the overlay is on for at least one canvas. The View toggle shows
// this, and switching it flips every canvas together -- a panel button has no
// canvas of its own to act on, and "some are on" is not a state a checkbox can
// express honestly.
int mayara_pi::OverlaySel(int canvas) const {
  auto it = m_overlay_sel.find(canvas);
  return it == m_overlay_sel.end() ? kOverlayAll : it->second;
}

// The radars this canvas draws. "All" is every shown radar, which the caller
// then sorts by range so the shorter one nests inside the longer.
std::vector<int> mayara_pi::OverlayRadars(int canvas) const {
  std::vector<int> out;
  if (!m_client) return out;
  const int sel = OverlaySel(canvas);
  if (sel == kOverlayNone) return out;
  for (int i : m_client->ShownRadars())
    if (sel == kOverlayAll || sel == i) out.push_back(i);
  return out;
}

bool mayara_pi::OverlayOnAny() const {
  const int n = GetCanvasCount();
  for (int c = 0; c < (n > 0 ? n : 1); ++c)
    if (OverlayOn(c)) return true;
  return false;
}

void mayara_pi::SetOverlayAll(bool on) {
  const int n = GetCanvasCount();
  m_overlay_sel.clear();
  if (!on)
    for (int c = 0; c < (n > 0 ? n : 1); ++c) m_overlay_sel[c] = kOverlayNone;
  // Every canvas's outer radar may just have changed (or gone away). A stale
  // cached "want" that happens to match the new radar's would wrongly look
  // like Range Auto already did its job on it.
  m_chart_range_last_want.clear();
  SaveConfig();
}

// With two radars nested on one canvas, the inner picture is only useful if it
// is meaningfully shorter than the outer. This keeps it at the settable range
// closest to a quarter of the longer one -- radars accept only the ranges in
// their own schema, so an exact quarter is usually not one of them.
void mayara_pi::SyncAutoRange() {
  if (!m_prefs.nest_range || !m_client) return;
  // Only when some canvas actually nests them; otherwise the two radars are
  // independent pictures and their ranges are the operator's business.
  bool nested = false;
  const int n = GetCanvasCount();
  for (int c = 0; c < (n > 0 ? n : 1); ++c)
    if (OverlaySel(c) == kOverlayAll && OverlayRadars(c).size() > 1)
      nested = true;
  if (!nested) return;

  // A steers B, in the order the radars appear in the menu -- not "whichever is
  // currently longer", which would swap the roles the moment B is ranged out
  // past A and leave the two chasing each other.
  std::vector<int> shown = m_client->ShownRadars();
  if (shown.size() < 2) return;
  const int outer = shown[0], inner = shown[1];

  RadarControls* oc = m_client->ControlsAt(outer);
  RadarControls* ic = m_client->ControlsAt(inner);
  if (!oc || !ic) return;
  const double outer_m = oc->Value("range").value;
  if (outer_m <= 0) return;
  const double want = outer_m / 4.0;

  std::vector<int> vals;
  for (const auto& d : ic->Schema())
    if (d.id == "range") {
      vals = d.validValues;
      break;
    }
  if (vals.empty()) return;
  int best = vals[0];
  for (int v : vals)
    if (std::fabs(v - want) < std::fabs(best - want)) best = v;

  const double cur = ic->Value("range").value;
  if (std::fabs(cur - best) < 1.0) return;  // already there
  m_client->SetControlAt(inner, "range",
                         "{\"value\":" + std::to_string(best) + "}");
}

// The controls on their own, drawn over the chart itself: a real child window
// of the canvas, so it floats above the chart without being a window of its
// own to manage, and it goes away with one click. Clicking the menu entry for
// the canvas it is already on closes it again.
// Let the chart's own zoom drive the radar: the operator zooms once and the
// picture follows. The target is the shortest range the radar offers that
// still covers the chart, so zooming in steps the radar down with it.
// --- Feeding OpenCPN -------------------------------------------------------
// OpenCPN already knows how to draw a heading and a tracked target; what it
// lacks is the radar's version of them. These push NMEA 0183 into its own
// stream, so the radar's heading can drive the chart and its targets land in
// OpenCPN's target list rather than only in our picture.

// $-sentence with the XOR checksum appended. `body` excludes the leading '$'.
static wxString NmeaSentence(const std::string& body) {
  unsigned char sum = 0;
  for (char c : body) sum ^= static_cast<unsigned char>(c);
  return wxString::Format("$%s*%02X\r\n", body.c_str(), sum);
}

// A number with a fixed number of decimals, whatever the locale thinks a
// decimal point is: NMEA says '.', and LC_NUMERIC would happily write ','.
static std::string NmeaNum(double v, int decimals) {
  char buf[32];
  std::snprintf(buf, sizeof(buf), "%.*f", decimals, v);
  for (char* p = buf; *p; ++p)
    if (*p == ',') *p = '.';
  return buf;
}

void mayara_pi::FeedHeading() {
  if (!m_feed_heading || !m_client) return;
  // The radar's own heading, not OpenCPN's: feeding its own value back to it
  // would be a loop that says nothing.
  double hdt = 0.0;
  bool have = false;
  for (int i = 0; i < m_client->RadarCount() && !have; ++i) {
    RadarState* st = m_client->StateAt(i);
    if (st && st->Heading(hdt)) have = true;
  }
  // Nothing to say is worth saying once: a radar that reports no heading of
  // its own is the usual reason this feed appears to do nothing.
  if (!have) {
    if (!m_feed_hdt_silent) {
      m_feed_hdt_silent = true;
      Log(1, "HDT feed is on, but no radar reports a heading; nothing sent");
    }
    return;
  }
  m_feed_hdt_silent = false;
  while (hdt < 0) hdt += 360.0;
  while (hdt >= 360.0) hdt -= 360.0;
  const wxString sentence = NmeaSentence("RAHDT," + NmeaNum(hdt, 1) + ",T");
  PushNMEABuffer(sentence);
  // Once a minute: enough to prove it is being sent and what it says, without
  // a line a second. Whether OpenCPN then *uses* it is a question for its
  // source priorities, not for us -- another source may outrank ours.
  if (++m_feed_hdt_count % 60 == 1)
    Log(2, wxString::Format("sent %s (%llu so far)", sentence.Strip(wxString::both),
                            static_cast<unsigned long long>(m_feed_hdt_count)));
}

void mayara_pi::FeedTargets() {
  if (!m_feed_targets || !m_client) return;
  int sent = 0;
  const wxDateTime now = wxDateTime::UNow().ToUTC();
  const std::string stamp = NmeaNum(now.GetHour() * 10000 + now.GetMinute() * 100 +
                                        now.GetSecond() +
                                        now.GetMillisecond() / 1000.0,
                                    2);

  for (int i = 0; i < m_client->RadarCount(); ++i) {
    for (const RadarTarget& t : m_client->TargetsAt(i)) {
      // TTM's target number is two digits, and target ids are not: hand out
      // small numbers and keep them for as long as the target lives, so a
      // target does not change identity under OpenCPN mid-track.
      const std::string key = std::to_string(i) + ":" + std::to_string(t.id);
      auto it = m_ttm_number.find(key);
      if (it == m_ttm_number.end()) {
        if (t.status == RadarTarget::kLost) continue;  // no number to spare
        int n = 0;
        std::set<int> used;
        for (const auto& kv : m_ttm_number) used.insert(kv.second);
        while (n < 100 && used.count(n)) ++n;
        if (n >= 100) continue;  // all 100 in use; drop this one rather than
                                 // steal a number a tracked target is using
        it = m_ttm_number.emplace(key, n).first;
      }
      const int num = it->second;
      if (t.status == RadarTarget::kLost) m_ttm_number.erase(key);

      double brg = t.bearing_deg;
      while (brg < 0) brg += 360.0;
      while (brg >= 360.0) brg -= 360.0;
      const char status = t.status == RadarTarget::kLost      ? 'L'
                          : t.status == RadarTarget::kAcquiring ? 'Q'
                                                              : 'T';
      char nbuf[8];
      std::snprintf(nbuf, sizeof(nbuf), "%02d", num);
      std::string body = std::string("RATTM,") + nbuf;
      body += "," + NmeaNum(t.distance_m / 1852.0, 3);
      body += "," + NmeaNum(brg, 1) + ",T";
      body += "," + (t.has_motion ? NmeaNum(t.speed_kn, 1) : std::string());
      body += "," + (t.has_motion ? NmeaNum(t.course_deg, 1) : std::string());
      body += ",T";
      body += "," + (t.has_danger ? NmeaNum(t.cpa_m / 1852.0, 3) : std::string());
      body += "," + (t.has_danger ? NmeaNum(t.tcpa_s / 60.0, 1) : std::string());
      body += ",N,,";  // speed/distance units, then the (unnamed) target
      body += status;
      body += ",,";  // reference target: none
      body += stamp;
      body += ",";
      body += t.manual ? 'M' : 'A';
      PushNMEABuffer(NmeaSentence(body));
      ++sent;
    }
  }
  if (sent && ++m_feed_ttm_ticks % 60 == 1)
    Log(2, wxString::Format("sent %d TTM sentence(s) this tick", sent));
}

// --- Echo colour profiles --------------------------------------------------
// The four built-ins are rebuilt from code every time, so a later release can
// improve one and every user gets it; only the profiles a user made are stored.
void mayara_pi::LoadPalettes(wxFileConfig* cfg) {
  m_palettes = BuiltinPalettes();
  long count = 0;
  cfg->Read("PaletteCount", &count, 0);
  for (long i = 0; i < count; ++i) {
    wxString line;
    if (!cfg->Read(wxString::Format("Palette%ld", i), &line) || line.IsEmpty())
      continue;
    RadarPalette p;
    if (!PaletteFromString(std::string(line.utf8_str()), &p)) continue;
    // A user profile never shadows a built-in name: the built-in would become
    // unreachable and the list would show the same name twice.
    bool clash = false;
    for (const RadarPalette& b : m_palettes)
      if (b.name == p.name) clash = true;
    if (clash) p.name += " (copy)";
    m_palettes.push_back(p);
  }
  wxString active;
  cfg->Read("PaletteActive", &active, "Standard Mayara");
  m_palette_active = std::string(active.utf8_str());
  // The maker-named profiles were replaced by plain hues; keep a config that
  // selected one pointing at the nearest thing rather than silently resetting.
  if (m_palette_active == "Navico red" || m_palette_active == "Navico yellow")
    m_palette_active = "Yellow";
  else if (m_palette_active == "Garmin")
    m_palette_active = "Green";
  else if (m_palette_active == "Furuno")
    m_palette_active = "Standard Mayara";
}

void mayara_pi::SavePalettes(wxFileConfig* cfg) {
  long n = 0;
  for (const RadarPalette& p : m_palettes) {
    if (p.builtin) continue;
    cfg->Write(wxString::Format("Palette%ld", n),
               wxString::FromUTF8(PaletteToString(p).c_str()));
    ++n;
  }
  cfg->Write("PaletteCount", n);
  cfg->Write("PaletteActive", wxString::FromUTF8(m_palette_active.c_str()));
}

const RadarPalette& mayara_pi::ActivePalette() const {
  for (const RadarPalette& p : m_palettes)
    if (p.name == m_palette_active) return p;
  return m_palettes.front();  // the built-ins are always there
}

void mayara_pi::ApplyPalette() {
  if (!m_client) return;
  m_client->SetPalette(ActivePalette());
  // The pictures redraw on their own timer; the chart overlay only when the
  // chart does, and a colour change is not something it would notice.
  for (MayaraPpiWindow* win : m_windows)
    if (win) win->Refresh(false);
  if (wxWindow* c = GetOCPNCanvasWindow()) c->Refresh(false);
}

// --- Diagnostics -----------------------------------------------------------

static int64_t DiagNowMs() {
  return std::chrono::duration_cast<std::chrono::milliseconds>(
             std::chrono::steady_clock::now().time_since_epoch())
      .count();
}

// Heading, in the order the operator asked for it. Returning false is a real
// answer: without a heading the picture cannot be laid on the chart at all,
// and drawing it at 0 degrees would be a confident lie.
bool mayara_pi::ResolveHeading(int radar, double* deg, wxString* source) const {
  auto give = [&](double d, const wxString& from) {
    while (d < 0) d += 360.0;
    while (d >= 360.0) d -= 360.0;
    if (deg) *deg = d;
    if (source) *source = from;
    return true;
  };

  if (m_diag.heading_source == Diagnostics::kFixedHeading)
    return give(m_diag.fixed_heading, _("fixed"));

  // OpenCPN's, if it is a real number and has not gone stale.
  if (m_diag.heading_source != Diagnostics::kRadarOnly && m_nav.has_hdt) {
    const int64_t age = DiagNowMs() - m_hdt_ms;
    if (m_diag.heading_timeout_s <= 0 ||
        age <= m_diag.heading_timeout_s * 1000)
      return give(m_nav.hdt, _("OpenCPN"));
  }

  // The radar's own, derived from the bearing stamped into its spokes.
  if (m_diag.heading_source != Diagnostics::kOpenCpnOnly && m_client) {
    const int first = radar >= 0 ? radar : 0;
    const int last = radar >= 0 ? radar : m_client->RadarCount() - 1;
    for (int i = first; i <= last; ++i) {
      RadarState* st = m_client->StateAt(i);
      double h = 0.0;
      if (!st || !st->Heading(h)) continue;
      const int64_t age = st->HeadingAgeMs();
      if (m_diag.heading_timeout_s > 0 && age >= 0 &&
          age > m_diag.heading_timeout_s * 1000)
        continue;
      return give(h, _("radar"));
    }
  }

  // Course over ground is not heading -- it differs by leeway and set -- so it
  // is only ever used when asked for, and it says so.
  if (m_diag.cog_as_heading && m_nav.has_cog)
    return give(m_nav.cog, _("COG"));

  return false;
}

bool mayara_pi::ResolvePosition(int radar, double* lat, double* lon,
                                wxString* source) const {
  if (m_diag.fixed_position) {
    if (lat) *lat = m_diag.fixed_lat;
    if (lon) *lon = m_diag.fixed_lon;
    if (source) *source = _("fixed");
    return true;
  }
  if (m_nav.valid) {
    if (lat) *lat = m_nav.lat;
    if (lon) *lon = m_nav.lon;
    if (source) *source = _("OpenCPN");
    return true;
  }
  // The radar stamps its own position into the spoke data on sets that know
  // it, which is what makes the overlay work on a boat where OpenCPN has no
  // fix of its own.
  if (m_client) {
    const int first = radar >= 0 ? radar : 0;
    const int last = radar >= 0 ? radar : m_client->RadarCount() - 1;
    for (int i = first; i <= last; ++i) {
      RadarState* st = m_client->StateAt(i);
      double a = 0.0, o = 0.0;
      if (st && st->Position(a, o)) {
        if (lat) *lat = a;
        if (lon) *lon = o;
        if (source) *source = _("radar");
        return true;
      }
    }
  }
  return false;
}

