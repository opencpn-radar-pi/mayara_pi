static const char* kConfigGroup = "/PlugIns/mayara";

void mayara_pi::LoadConfig() {
  wxFileConfig* cfg = GetOCPNConfigObject();
  if (!cfg) return;
  cfg->SetPath(kConfigGroup);
  int windows = 1;
  cfg->Read("WindowsCount", &windows, 1);
  m_windows_count = windows < 1 ? 1 : windows;
  // "OverlayOffCanvases" is a comma list; the old single OverlayEnabled flag is
  // still honoured so an existing config does not silently switch the overlay
  // back on.
  // "OverlaySel" is "canvas:selection;..."; the older OverlayOffCanvases list
  // and the original single flag are still honoured so an existing config keeps
  // its meaning.
  m_overlay_sel.clear();
  bool overlay = true;
  cfg->Read("OverlayEnabled", &overlay, true);
  wxString sel;
  if (cfg->Read("OverlaySel", &sel) && !sel.IsEmpty()) {
    wxStringTokenizer tok(sel, ";");
    while (tok.HasMoreTokens()) {
      const wxString pair = tok.GetNextToken();
      const int colon = pair.Find(':');
      long c = 0, v = 0;
      if (colon != wxNOT_FOUND && pair.Left(colon).ToLong(&c) &&
          pair.Mid(colon + 1).ToLong(&v))
        m_overlay_sel[static_cast<int>(c)] = static_cast<int>(v);
    }
  } else {
    wxString off;
    if (cfg->Read("OverlayOffCanvases", &off) && !off.IsEmpty()) {
      wxStringTokenizer tok(off, ",");
      while (tok.HasMoreTokens()) {
        long c = 0;
        if (tok.GetNextToken().ToLong(&c))
          m_overlay_sel[static_cast<int>(c)] = kOverlayNone;
      }
    } else if (!overlay) {
      m_overlay_sel[0] = kOverlayNone;
    }
  }
  long hz = 5, autohide = 0;
  bool reverse_zoom = false;
  cfg->Read("RefreshHz", &hz, 5);
  cfg->Read("ReverseZoom", &reverse_zoom, false);
  cfg->Read("MenuAutoHide", &autohide, 0);
  long alpha = 100;
  bool ozones = true;
  cfg->Read("OverlayAlpha", &alpha, 100);
  cfg->Read("OverlayZones", &ozones, true);
  bool arange = false;
  cfg->Read("AutoRange", &arange, false);
  m_prefs.auto_range = arange;
  m_prefs.overlay_alpha =
      static_cast<int>(alpha < 25 ? 25 : (alpha > 100 ? 100 : alpha));
  m_prefs.overlay_zones = ozones;
  m_prefs.refresh_hz = static_cast<int>(hz < 1 ? 1 : (hz > 15 ? 15 : hz));
  m_prefs.reverse_zoom = reverse_zoom;
  m_prefs.menu_autohide =
      static_cast<int>(autohide < 0 ? 0 : (autohide > 2 ? 2 : autohide));
  // Per-radar orientation: "id=mode;id=mode;..."
  m_orient.clear();
  wxString orient;
  if (cfg->Read("Orientations", &orient) && !orient.IsEmpty()) {
    wxStringTokenizer tok(orient, ";");
    while (tok.HasMoreTokens()) {
      const wxString pair = tok.GetNextToken();
      const int eq = pair.Find('=');
      if (eq == wxNOT_FOUND) continue;
      long m = 0;
      if (pair.Mid(eq + 1).ToLong(&m) && m >= 0 && m <= 2)
        m_orient[std::string(pair.Left(eq).mb_str())] = static_cast<int>(m);
    }
  }
  // Per-radar echo threshold: "id=level;id=level;..."
  m_threshold.clear();
  wxString thresh;
  if (cfg->Read("Thresholds", &thresh) && !thresh.IsEmpty()) {
    wxStringTokenizer tok(thresh, ";");
    while (tok.HasMoreTokens()) {
      const wxString pair = tok.GetNextToken();
      const int eq = pair.Find('=');
      if (eq == wxNOT_FOUND) continue;
      long m = 0;
      if (pair.Mid(eq + 1).ToLong(&m) && m >= 0 && m <= 2)
        m_threshold[std::string(pair.Left(eq).mb_str())] = static_cast<int>(m);
    }
  }
  bool shown = false;
  cfg->Read("WindowsVisible", &shown, false);
  m_windows_visible = shown;  // restored on the next fix (see SetPositionFixEx)
  bool docked = false;
  cfg->Read("Docked", &docked, false);
  m_docked = docked;
  wxString url;
  cfg->Read("ServerUrl", &url);
  m_saved_server_url = std::string(url.mb_str());
  wxString xurl;
  cfg->Read("ExplicitServerUrl", &xurl);
  m_explicit_server_url = std::string(xurl.mb_str());
  wxString declined;
  cfg->Read("LocalServerUpdateDeclined", &declined);
  m_update_declined = std::string(declined.mb_str());
  // Signal K device access.
  wxString s;
  cfg->Read("SignalKClientId", &s);
  m_client_id = std::string(s.mb_str());
  if (m_client_id.empty()) {
    // A stable identity for this OpenCPN installation, so an approval given
    // once in the Signal K admin UI keeps working.
    std::random_device rd;
    wxString id = "mayara-pi-";
    for (int i = 0; i < 4; ++i) id += wxString::Format("%08x", rd());
    m_client_id = std::string(id.mb_str());
    cfg->Write("SignalKClientId", id);
    cfg->Flush();
  }
  s.Clear();
  cfg->Read("SignalKToken", &s);
  m_sk_token = std::string(s.mb_str());
  s.Clear();
  cfg->Read("SignalKTokenServer", &s);
  m_sk_token_server = std::string(s.mb_str());
  s.Clear();
  cfg->Read("SignalKPendingHref", &s);
  m_sk_pending_href = std::string(s.mb_str());
  s.Clear();
  cfg->Read("SignalKPendingServer", &s);
  m_sk_pending_server = std::string(s.mb_str());
}

int mayara_pi::OrientationFor(const std::string& radar_id) const {
  auto it = m_orient.find(radar_id);
  return it != m_orient.end() ? it->second : 0;
}

void mayara_pi::SetOrientationFor(const std::string& radar_id, int mode) {
  m_orient[radar_id] = mode;
  SaveConfig();
}

int mayara_pi::ThresholdFor(const std::string& radar_id) const {
  auto it = m_threshold.find(radar_id);
  return it != m_threshold.end() ? it->second : 0;
}

void mayara_pi::SetThresholdFor(const std::string& radar_id, int level) {
  m_threshold[radar_id] = level;
  SaveConfig();
}

// Snapshot geometry + visibility while the windows are definitely alive. wx may
// destroy top-level windows before DeInit, so we never read them at shutdown.
void mayara_pi::CaptureWindowState() {
  if (m_docked) {
    // Docked: remember each pane's AUI layout (dock side, float pos/size, ...).
    m_persp_cache.clear();
    if (m_aui)
      for (MayaraPpiWindow* w : m_windows) {
        if (!w) continue;
        wxAuiPaneInfo& pane = m_aui->GetPane(w);
        m_persp_cache.push_back(pane.IsOk() ? m_aui->SavePaneInfo(pane)
                                            : wxString());
      }
    return;
  }
  m_geom_cache.clear();
  for (MayaraPpiWindow* w : m_windows)
    if (w) m_geom_cache.push_back(w->WindowRect());
}

void mayara_pi::SaveWindowState() {
  wxFileConfig* cfg = GetOCPNConfigObject();
  if (!cfg) return;
  cfg->SetPath(kConfigGroup);
  cfg->Write("WindowsVisible", m_windows_visible);
  cfg->Write("WinCount", static_cast<int>(m_geom_cache.size()));
  for (size_t i = 0; i < m_geom_cache.size(); ++i) {
    const wxRect& r = m_geom_cache[i];
    const int k = static_cast<int>(i);
    cfg->Write(wxString::Format("Win%d_x", k), r.x);
    cfg->Write(wxString::Format("Win%d_y", k), r.y);
    cfg->Write(wxString::Format("Win%d_w", k), r.width);
    cfg->Write(wxString::Format("Win%d_h", k), r.height);
  }
  // Docked pane layouts (AUI perspective per pane). The "R" key version was
  // bumped when the default dock moved to a full-height right column.
  cfg->Write("PaneRCount", static_cast<int>(m_persp_cache.size()));
  for (size_t i = 0; i < m_persp_cache.size(); ++i)
    cfg->Write(wxString::Format("PaneR%d", static_cast<int>(i)),
               m_persp_cache[i]);
  cfg->Flush();
}

bool mayara_pi::RestoreWindowGeometry() {
  wxFileConfig* cfg = GetOCPNConfigObject();
  if (!cfg) return false;
  cfg->SetPath(kConfigGroup);
  int wc = 0;
  cfg->Read("WinCount", &wc, 0);
  if (wc <= 0 || wc != static_cast<int>(m_windows.size())) return false;
  for (size_t i = 0; i < m_windows.size(); ++i) {
    if (!m_windows[i]) continue;
    const int k = static_cast<int>(i);
    int x, y, w, h;
    if (cfg->Read(wxString::Format("Win%d_x", k), &x) &&
        cfg->Read(wxString::Format("Win%d_y", k), &y) &&
        cfg->Read(wxString::Format("Win%d_w", k), &w) &&
        cfg->Read(wxString::Format("Win%d_h", k), &h) && w > 80 && h > 80)
      m_windows[i]->SetWindowRect(wxRect(x, y, w, h));
  }
  return true;
}

wxString mayara_pi::SavedPaneInfo(int index) const {
  wxFileConfig* cfg = GetOCPNConfigObject();
  if (!cfg) return wxString();
  cfg->SetPath(kConfigGroup);
  int pc = 0;
  cfg->Read("PaneRCount", &pc, 0);
  if (index < 0 || index >= pc) return wxString();
  wxString s;
  cfg->Read(wxString::Format("PaneR%d", index), &s);
  return s;
}

void mayara_pi::SaveConfig() {
  wxFileConfig* cfg = GetOCPNConfigObject();
  if (!cfg) return;
  cfg->SetPath(kConfigGroup);
  cfg->Write("WindowsCount", m_windows_count);
  cfg->Write("OverlayEnabled", OverlayOnAny());
  wxString sel;
  for (const auto& kv : m_overlay_sel)
    sel += wxString::Format("%d:%d;", kv.first, kv.second);
  cfg->Write("OverlaySel", sel);
  cfg->Write("RefreshHz", static_cast<long>(m_prefs.refresh_hz));
  cfg->Write("ReverseZoom", m_prefs.reverse_zoom);
  cfg->Write("MenuAutoHide", static_cast<long>(m_prefs.menu_autohide));
  cfg->Write("OverlayAlpha", static_cast<long>(m_prefs.overlay_alpha));
  cfg->Write("OverlayZones", m_prefs.overlay_zones);
  cfg->Write("AutoRange", m_prefs.auto_range);
  wxString orient;
  for (const auto& kv : m_orient)
    orient += wxString::Format("%s=%d;", kv.first.c_str(), kv.second);
  cfg->Write("Orientations", orient);
  wxString thresh;
  for (const auto& kv : m_threshold)
    thresh += wxString::Format("%s=%d;", kv.first.c_str(), kv.second);
  cfg->Write("Thresholds", thresh);
  cfg->Write("Docked", m_docked);
  cfg->Write("ServerUrl", wxString::FromUTF8(m_saved_server_url.c_str()));
  cfg->Write("ExplicitServerUrl",
             wxString::FromUTF8(m_explicit_server_url.c_str()));
  cfg->Write("LocalServerUpdateDeclined",
             wxString::FromUTF8(m_update_declined.c_str()));
  cfg->Flush();
}

// Keep the persisted Signal K access state in step with the client, and raise
// the approval dialog the first time a control write is refused.
void mayara_pi::SyncAccessConfig() {
  if (!m_client) return;
  bool dirty = false;
  const std::string token = m_client->AuthToken();
  if (token != m_sk_token) {
    m_sk_token = token;
    m_sk_token_server = m_client->AuthTokenServer();
    dirty = true;
  }
  const std::string href = m_client->PendingHref();
  if (href != m_sk_pending_href) {
    m_sk_pending_href = href;
    m_sk_pending_server = m_client->PendingServer();
    dirty = true;
  }
  if (dirty) {
    wxFileConfig* cfg = GetOCPNConfigObject();
    if (cfg) {
      cfg->SetPath(kConfigGroup);
      cfg->Write("SignalKToken", wxString::FromUTF8(m_sk_token.c_str()));
      cfg->Write("SignalKTokenServer",
                 wxString::FromUTF8(m_sk_token_server.c_str()));
      cfg->Write("SignalKPendingHref",
                 wxString::FromUTF8(m_sk_pending_href.c_str()));
      cfg->Write("SignalKPendingServer",
                 wxString::FromUTF8(m_sk_pending_server.c_str()));
      cfg->Flush();
    }
  }

  const MayaraClient::AuthState state = m_client->Auth();
  // The radar silently ignoring the transmit button is the worst outcome, so
  // explain it as soon as the server refuses a write.
  if (!m_access_dialog && !m_access_dismissed &&
      (state == MayaraClient::AuthState::kNeeded ||
       state == MayaraClient::AuthState::kPending))
    ShowAccessDialog();
  UpdateAccessDialog();
}

