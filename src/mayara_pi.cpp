static wxBitmap RadarIcon(int px) {
  wxBitmapBundle bb = wxBitmapBundle::FromSVG(kRadarSvg, wxSize(px, px));
  if (bb.IsOk()) return bb.GetBitmap(wxSize(px, px));
  return wxBitmap(px, px, 32);  // transparent fallback
}

