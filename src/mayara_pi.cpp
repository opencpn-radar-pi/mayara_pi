void mayara_pi::OnContextMenuItemCallback(int id) {
  // The canvas is whatever the pointer was over when the menu opened; hold it,
  // because the pointer moves onto the menu itself from here on.
  const int canvas = m_menu_canvas;
  if (id == m_mi_overlay) {
    // Not from inside the host menu's own event handler: let it close first.
    if (m_parent_window)
      m_parent_window->CallAfter([this, canvas]() { ShowOverlayMenu(canvas); });
  } else if (id == m_mi_menu) {
    ShowRadarMenu(canvas);
  } else if (id == m_mi_ppi) {
    // Right-clicking the canvas to get here always makes the OpenCPN main
    // frame the active window first, so a floating PPI window could never be
    // "active" at this point -- basing the decision on window focus (as this
    // used to) meant it could never detect "already showing" and always fell
    // through to raise a window that needed no raising. Shown is shown,
    // focused or not; RaisePpiWindows still raises it when it was hidden.
    if (AnyWindowShown())
      TogglePpiWindow();
    else
      RaisePpiWindows();
  }
}

// Called just before the canvas context menu is shown; sync the check marks
// to the live state.
void mayara_pi::PrepareContextMenu(int canvasIndex) {
  // The menu item acts on the canvas whose menu this is, so remember it: the
  // callback that follows is not told which canvas it came from.
  m_menu_canvas = canvasIndex;
  RefreshContextMenu(canvasIndex);
}

// OpenCPN copies our items' labels and check marks when it builds the popup,
// so everything shown here has to be right before the menu opens. It calls
// PrepareContextMenu for that, but only for API versions it knows about, so
// the heartbeat runs this as well against the canvas under the pointer.
void mayara_pi::RefreshContextMenu(int canvas) {
  if (m_mi_overlay_item) {
    // Name the canvas only when there is more than one, so the single-canvas
    // case does not carry a number that means nothing.
    const wxString what = OverlayLabel(canvas);
    m_mi_overlay_item->SetItemLabel(
        GetCanvasCount() > 1
            ? wxString::Format(_("Mayara radar overlay (chart %d): %s"),
                               canvas + 1, what)
            : wxString::Format(_("Mayara radar overlay: %s"), what));
  }
  if (m_mi_ppi_item)
    m_mi_ppi_item->SetItemLabel(AnyWindowShown() ? _("Hide Mayara PPI")
                                                 : _("Show Mayara PPI"));
}

// What this canvas is currently set to, for the menu entry.
wxString mayara_pi::OverlayLabel(int canvas) const {
  const int sel = OverlaySel(canvas);
  if (sel == kOverlayNone) return _("none");
  if (sel == kOverlayAll) return _("all radars");
  const std::vector<std::string> names =
      m_client ? m_client->RadarNames() : std::vector<std::string>();
  if (sel >= 0 && sel < static_cast<int>(names.size()))
    return wxString::FromUTF8(names[sel].c_str());
  return wxString::Format(_("radar %d"), sel + 1);
}

// Our own popup, on the canvas that was right-clicked. Ours to build and ours
// to read, so it works whatever the host does with plugin submenus.
void mayara_pi::ShowOverlayMenu(int canvas) {
  if (!m_client) return;
  const std::vector<std::string> names = m_client->RadarNames();
  wxWindow* cw = GetCanvasByIndex(canvas);
  if (!cw) cw = GetOCPNCanvasWindow();
  if (!cw) return;

  wxMenu menu;
  menu.AppendRadioItem(m_mi_ov_none, _("None"));
  const int shown = std::min(static_cast<int>(names.size()), kMaxMenuRadars);
  for (int i = 0; i < shown; ++i)
    menu.AppendRadioItem(m_mi_ov_radar[i], wxString::FromUTF8(names[i].c_str()));
  if (shown > 1) menu.AppendRadioItem(m_mi_ov_all, _("All radars"));

  const int sel = OverlaySel(canvas);
  int on = m_mi_ov_none;
  if (sel == kOverlayAll && shown > 1)
    on = m_mi_ov_all;
  else if (sel >= 0 && sel < shown)
    on = m_mi_ov_radar[sel];
  if (wxMenuItem* it = menu.FindItem(on)) it->Check(true);

  const int got =
      cw->GetPopupMenuSelectionFromUser(menu, cw->ScreenToClient(wxGetMousePosition()));
  if (got == wxID_NONE) return;  // dismissed

  int now = kOverlayNone;
  if (got == m_mi_ov_all) {
    now = kOverlayAll;
  } else {
    for (int i = 0; i < kMaxMenuRadars; ++i)
      if (got == m_mi_ov_radar[i]) now = i;
  }
  m_overlay_sel[canvas] = now;
  // The radar just put on this canvas has never had Range Auto act on it --
  // forget what the previous one last asked for, or a coincidentally equal
  // value would wrongly look like "already done".
  m_chart_range_last_want.erase(canvas);
  SaveConfig();
  // Asking to see a radar on the chart means asking it to run: a radar in
  // standby would draw nothing. One-shot, on the selection itself -- putting
  // it back in standby afterwards is the operator's call and is left alone.
  for (int i : OverlayRadars(canvas)) {
    RadarControls* c = m_client->ControlsAt(i);
    if (!c) continue;
    const ControlValue pw = c->Value("power");
    if (pw.has_value && pw.value < 2.0)
      m_client->SetControlAt(i, "power", "{\"value\":2}");
  }
  SyncAutoRange();
  RefreshContextMenu(canvas);
  GetOCPNCanvasWindow()->Refresh(false);
}

// Right-clicking pops the menu where the pointer is, so the canvas under the
// pointer is the canvas the menu belongs to.
int mayara_pi::CanvasUnderMouse() const {
  const wxPoint p = wxGetMousePosition();
  const int n = GetCanvasCount();
  for (int i = 0; i < n; ++i) {
    wxWindow* w = GetCanvasByIndex(i);
    if (!w) continue;
    if (wxRect(w->GetScreenPosition(), w->GetSize()).Contains(p)) return i;
  }
  return -1;
}

// Split the discovered radars into m_windows_count near-even groups. Window w
// gets radars [w*base + min(w,rem) ..], distributing the remainder to the first
// windows. Never more windows than radars.
std::vector<std::vector<int>> mayara_pi::RadarGroups() const {
  std::vector<std::vector<int>> groups;
  const int n = m_client ? m_client->RadarCount() : 0;
  if (n <= 0) return groups;
  const int w = std::max(1, std::min(m_windows_count, n));
  const int base = n / w, rem = n % w;
  int idx = 0;
  for (int g = 0; g < w; ++g) {
    const int count = base + (g < rem ? 1 : 0);
    std::vector<int> grp;
    for (int k = 0; k < count; ++k) grp.push_back(idx++);
    groups.push_back(std::move(grp));
  }
  return groups;
}

void mayara_pi::DestroyWindows(bool sync) {
  bool touched_aui = false;
  for (MayaraPpiWindow* win : m_windows) {
    if (!win) continue;
    win->ShowWindow(false);
    if (win->IsDocked()) {
      if (m_aui) {
        m_aui->DetachPane(win);
        touched_aui = true;
      }
      // sync: delete now so panel timers can't call a freed client during
      // teardown. async: defer (we may be inside a window's own handler).
      if (sync)
        delete win;
      else
        win->Destroy();
    } else if (wxFrame* f = win->HostFrame()) {
      if (sync)
        delete f;  // deletes its child content panel too
      else
        f->Destroy();
    }
  }
  if (touched_aui && m_aui) m_aui->Update();
  m_windows.clear();
}

bool mayara_pi::AnyWindowShown() const {
  for (MayaraPpiWindow* win : m_windows)
    if (win && win->IsWindowShown()) return true;
  return false;
}

void mayara_pi::ApplyThemeToWindows() {
  for (MayaraPpiWindow* win : m_windows)
    if (win) win->ApplyTheme(ThemeFor(m_color_scheme, m_menu_font_pt));
}

// (Re)create the radar windows from the current radar count and window count,
// preserving the user's show/hide intent.
void mayara_pi::RebuildWindows() {
  // Snapshot and persist current geometry before tearing down: the new
  // windows restore position from disk (RestoreWindowGeometry), which
  // otherwise only gets written at unload, so a move made earlier this
  // session -- not just in the last heartbeat tick -- would be lost.
  if (AnyWindowShown() && !m_ocpn_fullscreen) {
    CaptureWindowState();
    SaveWindowState();
  }
  DestroyWindows(/*sync=*/false);
  m_windows_radar_count = m_client ? m_client->RadarCount() : 0;
  std::vector<std::vector<int>> groups = RadarGroups();
  // No radars yet: still open one window bound to index 0 so the user sees the
  // "waiting for radar" UI; it starts showing radar 0 as soon as it connects.
  if (groups.empty()) groups.push_back({0});
  const bool docked = m_docked && m_aui;
  int pane_no = 0;
  for (const std::vector<int>& grp : groups) {
    MayaraPpiWindow* win = nullptr;
    if (docked) {
      win = new MayaraPpiWindow(m_aui->GetManagedWindow(), m_client.get(), grp);
      win->SetDockedHost(m_aui);
      const wxString pane_name = wxString::Format("mayara-%d", pane_no);
      wxAuiPaneInfo pane;
      pane.Name(pane_name)
          .Caption(win->Title())
          .CaptionVisible(true)
          .DestroyOnClose(false)
          .Right()
          .Layer(1)  // outer layer: a full-height column right of the charts
          .Dockable(true)
          .Floatable(true)
          .CloseButton(true)
          .MinSize(300, 240)
          .BestSize(420, 900);
      // Restore this pane's saved AUI layout, then re-assert identity/caption.
      const wxString saved = SavedPaneInfo(pane_no);
      if (!saved.IsEmpty()) {
        m_aui->LoadPaneInfo(saved, pane);
        pane.Name(pane_name).Caption(win->Title()).MinSize(320, 240);
      }
      // Shown/hidden is decided once, after every window in this rebuild
      // exists (see RestoreWindowShown()); AddPane just needs a starting
      // value so it has something to lay out from.
      pane.Hide();
      m_aui->AddPane(win, pane);
      ++pane_no;
    } else {
      // wxFRAME_FLOAT_ON_PARENT, not wxSTAY_ON_TOP: the latter floats above
      // every application on macOS, not just OpenCPN, which is why this was
      // off by default for a long time (see m_ppi_stay_on_top). This style
      // ties it to the specific parent it was created with; a frame's style
      // cannot be changed later, so toggling it rebuilds the window.
      const long style = wxDEFAULT_FRAME_STYLE |
                        (m_ppi_stay_on_top ? wxFRAME_FLOAT_ON_PARENT : 0);
      const wxSize initial = m_parent_window->FromDIP(wxSize(880, 560));
      auto* frame = new wxFrame(m_parent_window, wxID_ANY, wxEmptyString,
                                wxDefaultPosition, initial, style);
      win = new MayaraPpiWindow(frame, m_client.get(), grp);
      frame->SetTitle(win->Title());
      frame->SetMinSize(frame->FromDIP(wxSize(480, 320)));
      auto* fs = new wxBoxSizer(wxVERTICAL);
      fs->Add(win, 1, wxEXPAND);
      frame->SetSizer(fs);
      win->SetFloatingHost(frame);
      // The plugin owns the window; hide instead of destroying on close.
      // Captured and saved right away rather than left to the next heartbeat
      // tick: AnyWindowShown() goes false the instant the last window closes,
      // which would otherwise skip the periodic capture for this exact change.
      frame->Bind(wxEVT_CLOSE_WINDOW, [this, win](wxCloseEvent& e) {
        win->ShowWindow(false);
        e.Veto();
        CaptureWindowState();
        SaveWindowState();
      });
    }
    win->ApplyTheme(ThemeFor(m_color_scheme, m_menu_font_pt));
    win->SetOverlayControl([this]() { return OverlayOnAny(); },
                           [this](bool on) {
                             SetOverlayAll(on);
                             SaveConfig();
                             GetOCPNCanvasWindow()->Refresh(false);
                           });
    win->SetSettingsControl([this, win]() { ShowSettings(win); });
    win->SetAutoLayoutControl([this]() { AutoLayoutWindows(/*reflow=*/true); });
    win->SetDockControl([this]() { return m_docked; },
                        [this](bool on) {
                          if (on == m_docked) return;
                          m_docked = on;
                          SaveConfig();
                          // Recreate in the new host mode, but not from inside a
                          // window's own control handler.
                          if (m_parent_window)
                            m_parent_window->CallAfter(
                                [this]() { RebuildWindows(); });
                        });
    win->SetNavProvider([this]() { return m_nav; });
    win->SetAlarmSoundControl(
        [this]() { return m_guard_alarm_sound; },
        [this]() {
          m_guard_alarm_sound = !m_guard_alarm_sound;
          SaveConfig();
          // Every window shows this lozenge, not just the one clicked.
          for (MayaraPpiWindow* w : m_windows)
            if (w) w->Refresh();
        });
    win->SetHeadingProvider([this](int radar, double& deg) {
      return ResolveHeading(radar, &deg, nullptr);
    });
    // Costs nothing when logging is off: the panel only calls this when it is
    // set, and it is only set while the operator is asking.
    if (m_diag.log_level >= 2)
      win->SetPerfLog([this](const wxString& s) { Log(2, s); });
    win->SetOrientationHandlers(
        [this](const std::string& id) { return OrientationFor(id); },
        [this](const std::string& id, int o) { SetOrientationFor(id, o); });
    win->SetThresholdHandlers(
        [this](const std::string& id) { return ThresholdFor(id); },
        [this](const std::string& id, int l) { SetThresholdFor(id, l); });
    win->SetRangeAutoHandlers(
        [this](int idx) { return RadarInOverlay(idx); },
        [this](const std::string& id) { return RangeAutoFor(id); },
        [this](const std::string& id, bool on) { SetRangeAutoFor(id, on); });
    win->SetPrefsHandlers([this]() { return m_prefs; },
                          [this](const PpiPrefs& p) {
                            m_prefs = p;
                            SaveConfig();
                            // Every window shares these, not just this one.
                            for (MayaraPpiWindow* w : m_windows)
                              if (w) w->ApplyPrefs();
                          });
    m_windows.push_back(win);
  }
  // Each window's own shown/hidden state, when it matches this rebuild;
  // otherwise every window just follows the master toggle.
  if (!RestoreWindowShown())
    for (MayaraPpiWindow* w : m_windows)
      if (w) w->ShowWindow(m_windows_visible);
  if (docked) {
    m_aui->Update();
  } else if (!RestoreWindowGeometry() && m_windows.size() > 1) {
    // Floating: restore saved positions or tile so they don't stack.
    AutoLayoutWindows(/*reflow=*/false);
  }
}

// Tile the radar windows to fill `area`. Landscape: a row-major grid
// (left-right, then next row). Portrait: a single column, top-to-bottom.
static void TileInArea(const std::vector<MayaraPpiWindow*>& wins,
                       const wxRect& area) {
  const int n = static_cast<int>(wins.size());
  if (n == 0) return;
  const bool portrait = area.height > area.width;
  const int cols =
      portrait ? 1 : std::max(1, static_cast<int>(std::ceil(std::sqrt((double)n))));
  const int rows = (n + cols - 1) / cols;
  for (int i = 0; i < n; ++i) {
    const int c = i % cols, r = i / cols;
    const int x0 = area.x + area.width * c / cols;
    const int x1 = area.x + area.width * (c + 1) / cols;
    const int y0 = area.y + area.height * r / rows;
    const int y1 = area.y + area.height * (r + 1) / rows;
    if (wins[i]) wins[i]->SetWindowRect(wxRect(x0, y0, x1 - x0, y1 - y0));
  }
}

void mayara_pi::AutoLayoutWindows(bool reflow_ocpn) {
  if (m_windows.empty() || m_docked) return;  // AUI manages docked panes
  wxWindow* frame =
      m_parent_window ? wxGetTopLevelParent(m_parent_window) : nullptr;
  int main_disp = frame ? wxDisplay::GetFromWindow(frame) : wxNOT_FOUND;
  if (main_disp == wxNOT_FOUND) main_disp = 0;
  const unsigned n_disp = wxDisplay::GetCount();

  if (n_disp > 1) {
    // Put the radars on a display the main window is NOT on and let them share
    // that whole screen; the main window can then fill its own screen.
    unsigned target = (static_cast<unsigned>(main_disp) + 1) % n_disp;
    if (target == static_cast<unsigned>(main_disp)) target = 0;
    TileInArea(m_windows, wxDisplay(target).GetClientArea());
    if (reflow_ocpn && frame) {
      const wxRect ma =
          wxDisplay(static_cast<unsigned>(main_disp)).GetClientArea();
      frame->SetSize(ma.x, ma.y, ma.width, ma.height);
    }
    return;
  }

  // Single display: OpenCPN fills the left, radars stack down the right.
  const wxRect area =
      wxDisplay(static_cast<unsigned>(main_disp)).GetClientArea();
  const int radar_w = std::max(360, area.width * 38 / 100);
  if (reflow_ocpn && frame)
    frame->SetSize(area.x, area.y, area.width - radar_w, area.height);
  TileInArea(m_windows,
             wxRect(area.x + area.width - radar_w, area.y, radar_w,
                    area.height));
}

void mayara_pi::SyncRadarFullScreen(bool on) {
  if (m_docked) return;  // docked panes ride OpenCPN's own full screen
  if (!on) {
    for (MayaraPpiWindow* w : m_windows)
      if (w) w->LeaveFullScreen();
    return;
  }
  wxWindow* frame =
      m_parent_window ? wxGetTopLevelParent(m_parent_window) : nullptr;
  const int ocpn_disp = frame ? wxDisplay::GetFromWindow(frame) : wxNOT_FOUND;
  const unsigned nd = wxDisplay::GetCount();
  for (unsigned d = 0; d < nd; ++d) {
    if (static_cast<int>(d) == ocpn_disp) continue;  // leave OpenCPN's screen
    // Which shown radar windows currently live on display d.
    std::vector<MayaraPpiWindow*> on_d;
    for (MayaraPpiWindow* w : m_windows) {
      if (!w || !w->IsWindowShown()) continue;
      const wxRect r = w->WindowRect();
      const wxPoint mid(r.x + r.width / 2, r.y + r.height / 2);
      if (static_cast<unsigned>(wxDisplay::GetFromPoint(mid)) == d)
        on_d.push_back(w);
    }
    if (on_d.empty()) continue;
    const wxRect area = wxDisplay(d).GetGeometry();  // whole screen
    const int k = static_cast<int>(on_d.size());
    if (k == 1) {
      on_d[0]->EnterFullScreen(area, /*solo=*/true);
      continue;
    }
    // Two or more share the screen: split it (aspect decides the direction).
    const bool portrait = area.height > area.width;
    const int cols =
        portrait ? 1 : std::max(1, static_cast<int>(std::ceil(std::sqrt((double)k))));
    const int rows = (k + cols - 1) / cols;
    for (int i = 0; i < k; ++i) {
      const int c = i % cols, r = i / cols;
      const wxRect t(area.x + area.width * c / cols,
                     area.y + area.height * r / rows, area.width / cols,
                     area.height / rows);
      on_d[i]->EnterFullScreen(t, /*solo=*/false);
    }
  }
}

void mayara_pi::TogglePpiWindow() {
  const bool turning_on = !AnyWindowShown();
  // Capture each window's own state before they all go uniformly hidden
  // below -- once that happens every window reads the same, and the next
  // heartbeat tick has nothing left to tell them apart by (it skips the
  // capture entirely while the group is off; see the heartbeat above).
  if (!turning_on) CaptureWindowState();
  m_windows_visible = turning_on;
  const int radar_count = m_client ? m_client->RadarCount() : 0;
  if (m_windows_visible &&
      (m_windows.empty() || m_windows_radar_count != radar_count))
    RebuildWindows();  // build, or rebuild for a changed radar set
  if (m_windows_visible) {
    // Each window's own last shown/hidden state, when available -- a
    // blanket show would bring back a window closed on its own along with
    // the rest of the group. But this is an explicit "show" action: if
    // every window individually saved as hidden, restoring that literally
    // would show nothing and leave this same toggle unable to do anything
    // different next time -- fall back to showing everything instead.
    if (!RestoreWindowShown() || !AnyWindowShown())
      for (MayaraPpiWindow* win : m_windows)
        if (win) win->ShowWindow(true);
  } else {
    for (MayaraPpiWindow* win : m_windows)
      if (win) win->ShowWindow(false);
  }
  SetToolbarItemState(m_tool_id, m_windows_visible);
  if (m_windows_visible) CaptureWindowState();
}

// What this chart is showing, in real metres, for "chart scale sets range".
// Same Mercator correction as the overlay itself: view_scale_ppm is pixels per
// Mercator metre. The radius is half the shorter side, i.e. the largest circle
// the canvas holds -- a radar covering that covers the chart.
void mayara_pi::RecordCanvasRadius(PlugIn_ViewPort* vp, int canvasIndex) {
  const double coslat = std::max(0.02, std::cos(vp->clat * M_PI / 180.0));
  const double ppm = vp->view_scale_ppm / coslat;
  if (ppm > 0)
    m_canvas_radius_m[canvasIndex] =
        0.5 * std::min(vp->pix_width, vp->pix_height) / ppm;
}

// The radars this canvas draws, longest range first, so each is drawn as an
// annulus out to its own range and the shortest owns the middle.
std::vector<mayara_pi::OverlayItem> mayara_pi::OverlayItems(int canvasIndex) {
  std::vector<OverlayItem> items;
  for (int i : OverlayRadars(canvasIndex)) {
    RadarState* st = m_client->StateAt(i);
    if (st && st->RangeMeters() > 0) items.push_back({i, st->RangeMeters()});
  }
  std::sort(items.begin(), items.end(),
            [](const OverlayItem& a, const OverlayItem& b) {
              return a.range > b.range;
            });
  return items;
}

// The chart without OpenGL. OpenCPN calls this instead of the GL callback when
// hardware acceleration is off, and until now the plugin inherited the base
// class no-op -- so the overlay simply vanished, while the PPI (which never
// used GL: it is a wxPanel blitting a CPU-rendered bitmap) carried on. Same
// geometry as the GL path, same cached disc, drawn through wxGraphicsContext
// because a plain wxDC has no alpha.
bool mayara_pi::RenderOverlayMultiCanvas(wxDC& dc, PlugIn_ViewPort* vp,
                                         int canvasIndex, int priority) {
  if (!OverlayOn(canvasIndex) || !m_client || !vp || !vp->bValid) return false;
  if (priority != OVERLAY_LEGACY) return false;
  RecordCanvasRadius(vp, canvasIndex);
  const int n = m_client->RadarCount();
  if (n == 0) return false;
  if (static_cast<int>(m_overlay_bmp.size()) != n) m_overlay_bmp.assign(n, OverlayBmp{});

  std::vector<OverlayItem> items = OverlayItems(canvasIndex);
  if (items.empty()) return false;

  std::unique_ptr<wxGraphicsContext> gc(
      wxGraphicsContext::CreateFromUnknownDC(dc));
  if (!gc) return false;

  // The viewport is in physical pixels; a wxDC on a HiDPI screen draws in
  // logical points. GL never had to care -- its viewport is physical too -- so
  // on a Retina display every coordinate here was twice what it should be and
  // the picture ended up in the bottom-right corner. Measure the ratio from
  // the canvas rather than trusting GetContentScaleFactor(), which reports 1
  // for this DC.
  double scale = 1.0;
  if (wxWindow* cw = GetCanvasByIndex(canvasIndex)) {
    const wxSize cs = cw->GetClientSize();
    if (cs.x > 0 && vp->pix_width > 0)
      scale = static_cast<double>(cs.x) / vp->pix_width;
  }
  if (std::fabs(scale - 1.0) > 0.01) gc->Scale(scale, scale);

  // Once per canvas geometry, not once per frame: this says how the plugin is
  // mapping to the screen, and that only changes when the window does.
  if (m_diag.log_level >= 2) {
    const wxString shape = wxString::Format("%dx%d@%.3f", vp->pix_width,
                                            vp->pix_height, scale);
    if (m_last_dc_shape[canvasIndex] != shape) {
      m_last_dc_shape[canvasIndex] = shape;
      Log(2, wxString::Format("DC overlay: canvas %d, vp %dx%d, coordinate "
                              "scale %.3f",
                              canvasIndex, vp->pix_width, vp->pix_height,
                              scale));
    }
  }
  gc->BeginLayer(m_prefs.overlay_alpha / 100.0);
  bool drew = false;
  for (size_t k = 0; k < items.size(); ++k) {
    const double inner =
        (k + 1 < items.size())
            ? static_cast<double>(items[k + 1].range) / items[k].range
            : 0.0;
    if (DrawRadarOverlayDC(gc.get(), items[k].idx, vp, inner)) drew = true;
  }
  if (m_prefs.overlay_zones)
    for (const OverlayItem& it : items) DrawZonesOverlayDC(gc.get(), it.idx, vp);
  gc->EndLayer();
  return drew;
}

bool mayara_pi::DrawRadarOverlayDC(wxGraphicsContext* gc, int index,
                                   PlugIn_ViewPort* vp, double inner_frac) {
  RadarState* state = m_client->StateAt(index);
  if (!state) return false;
  const uint32_t range_m = state->RangeMeters();
  if (range_m == 0) return false;

  double lat = 0.0, lon = 0.0, heading = 0.0;
  if (!ResolvePosition(index, &lat, &lon, nullptr)) return false;
  if (!ResolveHeading(index, &heading, nullptr)) return false;

  wxPoint centre;
  GetCanvasPixLL(vp, &centre, lat, lon);
  if (std::abs(centre.x) > 1000000 || std::abs(centre.y) > 1000000) return false;
  const double coslat = std::max(0.02, std::cos(lat * M_PI / 180.0));
  const double radius_px = range_m * vp->view_scale_ppm / coslat;
  if (radius_px < 1.0) return false;
  const double rot_deg = heading + vp->rotation * 180.0 / M_PI;

  // Rasterising is per pixel on the CPU here, so the disc is capped and scaled
  // up by the blit when the chart is zoomed in past it. GL had no such worry.
  const int size = std::max(4, std::min(1536, static_cast<int>(radius_px * 2)));
  const int rot10 = static_cast<int>(rot_deg * 10) % 3600;

  OverlayBmp& cache = m_overlay_bmp[index];
  if (!cache.bmp.IsOk() || cache.gen != state->Generation() ||
      cache.size != size || cache.rot10 != rot10 ||
      std::fabs(cache.inner - inner_frac) > 0.001) {
    std::vector<uint8_t> rgba(static_cast<size_t>(size) * size * 4);
    uint64_t drawn_gen = 0;
    if (!state->RenderOverlayRGBA(rgba.data(), size, rot_deg, inner_frac,
                                  &drawn_gen))
      return false;
    // wxImage wants the colour and the alpha in separate buffers, and takes
    // ownership of both.
    unsigned char* rgb = static_cast<unsigned char*>(malloc(static_cast<size_t>(size) * size * 3));
    unsigned char* alpha = static_cast<unsigned char*>(malloc(static_cast<size_t>(size) * size));
    if (!rgb || !alpha) {
      free(rgb);
      free(alpha);
      return false;
    }
    for (size_t i = 0; i < static_cast<size_t>(size) * size; ++i) {
      rgb[i * 3 + 0] = rgba[i * 4 + 0];
      rgb[i * 3 + 1] = rgba[i * 4 + 1];
      rgb[i * 3 + 2] = rgba[i * 4 + 2];
      alpha[i] = rgba[i * 4 + 3];
    }
    cache.bmp = wxBitmap(wxImage(size, size, rgb, alpha));
    cache.gen = drawn_gen;  // what was drawn, not what has arrived since
    cache.size = size;
    cache.rot10 = rot10;
    cache.inner = inner_frac;
  }
  if (!cache.bmp.IsOk()) return false;
  gc->DrawBitmap(cache.bmp, centre.x - radius_px, centre.y - radius_px,
                 radius_px * 2, radius_px * 2);
  if (m_diag.log_level >= 2 && ++m_dc_frames % 100 == 0)
    Log(2, wxString::Format(
               "DC overlay: radar %d centre %d,%d radius %.0f raster %d "
               "rot %.1f",
               index, centre.x, centre.y, radius_px, size, rot_deg));
  return true;
}

void mayara_pi::DrawZonesOverlayDC(wxGraphicsContext* gc, int index,
                                   PlugIn_ViewPort* vp) {
  RadarControls* ctrl = m_client ? m_client->ControlsAt(index) : nullptr;
  if (!ctrl) return;
  double lat = 0.0, lon = 0.0, heading = 0.0;
  if (!ResolvePosition(index, &lat, &lon, nullptr)) return;
  if (!ResolveHeading(index, &heading, nullptr)) return;

  wxPoint centre;
  GetCanvasPixLL(vp, &centre, lat, lon);
  const double coslat = std::max(0.02, std::cos(lat * M_PI / 180.0));
  const double ppm = vp->view_scale_ppm / coslat;
  const double base = (heading + vp->rotation * 180.0 / M_PI) * M_PI / 180.0 -
                      M_PI / 2.0;

  const wxColour fill[2] = {wxColour(144, 238, 144, 64),
                            wxColour(173, 216, 230, 64)};
  const wxColour line[2] = {wxColour(0, 128, 0, 153), wxColour(0, 0, 255, 153)};
  const char* ids[2] = {"guardZone1", "guardZone2"};

  for (int z = 0; z < 2; ++z) {
    const ControlValue v = ctrl->Value(ids[z]);
    if (!v.has_enabled || !v.enabled) continue;
    if (v.endDistance <= v.startDistance) continue;
    const double r_in = v.startDistance * ppm, r_out = v.endDistance * ppm;
    if (r_out < 2) continue;
    double a0 = base + v.value, a1 = base + v.endValue;
    const bool whole = std::fabs(v.endValue - v.value) < 0.001;
    if (whole) a1 = a0 + 2.0 * M_PI;
    if (a1 < a0) a1 += 2.0 * M_PI;

    wxGraphicsPath path = gc->CreatePath();
    if (whole) {
      // Two full circles in one path: the odd-even rule leaves the hole.
      path.AddCircle(centre.x, centre.y, r_out);
      path.AddCircle(centre.x, centre.y, r_in);
    } else {
      path.MoveToPoint(centre.x + r_in * std::cos(a0),
                       centre.y + r_in * std::sin(a0));
      path.AddLineToPoint(centre.x + r_out * std::cos(a0),
                          centre.y + r_out * std::sin(a0));
      path.AddArc(centre.x, centre.y, r_out, a0, a1, true);
      path.AddLineToPoint(centre.x + r_in * std::cos(a1),
                          centre.y + r_in * std::sin(a1));
      path.AddArc(centre.x, centre.y, r_in, a1, a0, false);
      path.CloseSubpath();
    }
    gc->SetBrush(wxBrush(fill[z]));
    gc->SetPen(wxPen(line[z], 1));
    gc->FillPath(path, wxODDEVEN_RULE);
    gc->StrokePath(path);
  }
}

bool mayara_pi::RenderGLOverlayMultiCanvas(wxGLContext* pcontext,
                                           PlugIn_ViewPort* vp, int canvasIndex,
                                           int priority) {
  if (!OverlayOn(canvasIndex) || !m_client || !vp || !vp->bValid)
    return false;
  // OpenCPN calls this once per priority level per frame. Draw only at the
  // legacy chart-overlay layer; the higher passes (OVER_EMBOSS/OVER_UI) render
  // on top of the toolbar and chart bar, so drawing there paints over them.
  if (priority != OVERLAY_LEGACY) return false;
  RecordCanvasRadius(vp, canvasIndex);
  const int n = m_client->RadarCount();
  if (n == 0) return false;
  if (static_cast<int>(m_overlay_tex.size()) != n)
    m_overlay_tex.assign(n, OverlayTex{});

  // Collect radars that have data, sorted by range descending so the longest
  // range is drawn first and the shortest composites on top (short-range inner
  // disc, longer-range annulus beyond it).
  std::vector<OverlayItem> items = OverlayItems(canvasIndex);
  if (items.empty()) return false;

  glEnable(GL_BLEND);
  glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
  glEnable(GL_TEXTURE_2D);
  const float alpha = m_prefs.overlay_alpha / 100.0f;
  glColor4f(m_radar_intensity, m_radar_intensity, m_radar_intensity, alpha);

  // DrawRadarOverlay selects GL_MODELVIEW; glPopMatrix() undoes its matrix
  // contents but not that selection, so restore whatever mode the caller had
  // before handing control back.
  GLint saved_matrix_mode;
  glGetIntegerv(GL_MATRIX_MODE, &saved_matrix_mode);

  // Each radar is drawn as an annulus from the next-shorter shown radar's range
  // out to its own range; the shortest is a full disc. So the shorter radar
  // occludes the longer one within its radius.
  bool drew = false;
  for (size_t k = 0; k < items.size(); ++k) {
    const double inner =
        (k + 1 < items.size())
            ? static_cast<double>(items[k + 1].range) / items[k].range
            : 0.0;
    if (DrawRadarOverlay(items[k].idx, vp, inner)) drew = true;
  }

  glBindTexture(GL_TEXTURE_2D, 0);
  glDisable(GL_TEXTURE_2D);
  // Guard zones over the chart, in the same colours as the PPI so a zone reads
  // as the same thing in both places.
  if (m_prefs.overlay_zones)
    for (const OverlayItem& it : items) DrawZonesOverlay(it.idx, vp);
  glDisable(GL_BLEND);
  glMatrixMode(saved_matrix_mode);
  return drew;
}

bool mayara_pi::DrawRadarOverlay(int index, PlugIn_ViewPort* vp,
                                 double inner_frac) {
  RadarState* state = m_client->StateAt(index);
  if (!state) return false;
  const uint32_t range_m = state->RangeMeters();
  if (range_m == 0) return false;

  double lat = 0.0, lon = 0.0;
  if (!ResolvePosition(index, &lat, &lon, nullptr)) return false;

  OverlayTex& t = m_overlay_tex[index];
  if (t.tex == 0) {
    glGenTextures(1, &t.tex);
    t.gen = ~0ull;
  }
  const uint64_t gen = state->Generation();
  if (gen != t.gen) {
    const int size = state->CopyDisc(m_overlay_disc);
    if (size <= 0) return false;
    glBindTexture(GL_TEXTURE_2D, t.tex);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, size, size, 0, GL_RGBA,
                 GL_UNSIGNED_BYTE, m_overlay_disc.data());
    t.gen = gen;
  }

  wxPoint center;
  GetCanvasPixLL(vp, &center, lat, lon);
  if (std::abs(center.x) > 1000000 || std::abs(center.y) > 1000000)
    return false;
  // view_scale_ppm is pixels per *Mercator* metre, not per real metre:
  // OpenCPN's toSM() maps easting as dlon*R, leaving out the cos(lat) that
  // turns it into ground distance. The true local scale at latitude phi is
  // therefore view_scale_ppm / cos(phi) -- using the raw value draws the
  // overlay cos(lat) too small (40% short at 53N). radar_pi sidesteps this by
  // measuring pix_height against the great-circle height of the viewport; the
  // closed form is equivalent and exact at the radar's own latitude.
  const double coslat =
      std::max(0.02, std::cos(lat * M_PI / 180.0));  // clamped near the poles
  const double radius_px = range_m * vp->view_scale_ppm / coslat;
  if (radius_px < 1.0) return false;

  double heading = 0.0;
  if (!ResolveHeading(index, &heading, nullptr)) return false;
  const double rot_deg = heading + vp->rotation * 180.0 / M_PI;

  glBindTexture(GL_TEXTURE_2D, t.tex);
  glMatrixMode(GL_MODELVIEW);
  glPushMatrix();
  glTranslatef(center.x, center.y, 0.0f);
  glRotatef(rot_deg, 0.0f, 0.0f, 1.0f);
  glScalef(radius_px, radius_px, 1.0f);

  if (inner_frac <= 0.0) {
    // Full disc. Texcoord = (0.5 + 0.5*vertex).
    glBegin(GL_QUADS);
    glTexCoord2f(0.0f, 0.0f); glVertex2f(-1.0f, -1.0f);
    glTexCoord2f(1.0f, 0.0f); glVertex2f(1.0f, -1.0f);
    glTexCoord2f(1.0f, 1.0f); glVertex2f(1.0f, 1.0f);
    glTexCoord2f(0.0f, 1.0f); glVertex2f(-1.0f, 1.0f);
    glEnd();
  } else {
    // Annulus from inner_frac to 1.0 -- the inner circle is not drawn, so a
    // shorter-range radar occludes this one there.
    const int kSeg = 96;
    const double ri = std::min(0.999, inner_frac);
    glBegin(GL_TRIANGLE_STRIP);
    for (int i = 0; i <= kSeg; ++i) {
      const double a = 2.0 * M_PI * i / kSeg;
      const double c = std::cos(a), s = std::sin(a);
      const float ix = static_cast<float>(ri * c), iy = static_cast<float>(ri * s);
      const float ox = static_cast<float>(c), oy = static_cast<float>(s);
      glTexCoord2f(0.5f + 0.5f * ix, 0.5f + 0.5f * iy); glVertex2f(ix, iy);
      glTexCoord2f(0.5f + 0.5f * ox, 0.5f + 0.5f * oy); glVertex2f(ox, oy);
    }
    glEnd();
  }
  glPopMatrix();
  return true;
}

// The guard zones of one radar, drawn on the chart. Geometry matches
// DrawGuardZones on the PPI: bow-relative radians, metres, and the same
// 1/cos(lat) correction the echo disc uses -- without it a zone would sit at a
// different distance from the echoes it is watching.
void mayara_pi::DrawZonesOverlay(int index, PlugIn_ViewPort* vp) {
  RadarControls* ctrl = m_client ? m_client->ControlsAt(index) : nullptr;
  RadarState* state = m_client ? m_client->StateAt(index) : nullptr;
  if (!ctrl || !state) return;

  double lat = 0.0, lon = 0.0;
  if (!ResolvePosition(index, &lat, &lon, nullptr)) return;
  wxPoint centre;
  GetCanvasPixLL(vp, &centre, lat, lon);
  const double coslat = std::max(0.02, std::cos(lat * M_PI / 180.0));
  const double ppm = vp->view_scale_ppm / coslat;

  double heading = 0.0;
  if (!ResolveHeading(index, &heading, nullptr)) return;
  // Screen angle trails the bearing by 90 degrees, and the chart may be
  // rotated under us.
  const double base = (heading + vp->rotation * 180.0 / M_PI) * M_PI / 180.0 -
                      M_PI / 2.0;

  const float fill[2][4] = {{144 / 255.f, 238 / 255.f, 144 / 255.f, 0.25f},
                            {173 / 255.f, 216 / 255.f, 230 / 255.f, 0.25f}};
  const float line[2][4] = {{0.0f, 128 / 255.f, 0.0f, 0.6f},
                            {0.0f, 0.0f, 1.0f, 0.6f}};
  const char* ids[2] = {"guardZone1", "guardZone2"};

  for (int z = 0; z < 2; ++z) {
    const ControlValue v = ctrl->Value(ids[z]);
    if (!v.has_enabled || !v.enabled) continue;
    if (v.endDistance <= v.startDistance) continue;
    const double r_in = v.startDistance * ppm, r_out = v.endDistance * ppm;
    if (r_out < 2) continue;
    double a0 = base + v.value, a1 = base + v.endValue;
    if (std::fabs(v.endValue - v.value) < 0.001) a1 = a0 + 2.0 * M_PI;
    if (a1 < a0) a1 += 2.0 * M_PI;
    const int seg = std::max(8, static_cast<int>((a1 - a0) * 24));

    glColor4fv(fill[z]);
    glBegin(GL_TRIANGLE_STRIP);
    for (int i = 0; i <= seg; ++i) {
      const double a = a0 + (a1 - a0) * i / seg;
      const double c = std::cos(a), sn = std::sin(a);
      glVertex2f(centre.x + r_in * c, centre.y + r_in * sn);
      glVertex2f(centre.x + r_out * c, centre.y + r_out * sn);
    }
    glEnd();

    glColor4fv(line[z]);
    glLineWidth(1.0f);
    for (double r : {r_in, r_out}) {
      glBegin(GL_LINE_STRIP);
      for (int i = 0; i <= seg; ++i) {
        const double a = a0 + (a1 - a0) * i / seg;
        glVertex2f(centre.x + r * std::cos(a), centre.y + r * std::sin(a));
      }
      glEnd();
    }
  }
  glColor4f(1.0f, 1.0f, 1.0f, 1.0f);
}

void mayara_pi::SetPositionFixEx(PlugIn_Position_Fix_Ex& pfix) {
  m_ownship_lat = pfix.Lat;
  m_ownship_lon = pfix.Lon;
  m_ownship_cog = pfix.Cog;
  m_heading_true = pfix.Hdt;

  // NaN-tolerant fill of the shared nav state for the PPI overlays.
  m_nav.lat = pfix.Lat;
  m_nav.lon = pfix.Lon;
  m_nav.valid = !std::isnan(pfix.Lat) && !std::isnan(pfix.Lon) &&
                (pfix.Lat != 0.0 || pfix.Lon != 0.0);
  m_nav.has_cog = !std::isnan(pfix.Cog) && pfix.Cog >= 0.0;
  m_nav.cog = m_nav.has_cog ? pfix.Cog : 0.0;
  m_nav.sog = std::isnan(pfix.Sog) ? 0.0 : pfix.Sog;
  m_nav.has_hdt = !std::isnan(pfix.Hdt) && pfix.Hdt >= 0.0 && pfix.Hdt < 360.0;
  m_nav.hdt = m_nav.has_hdt ? pfix.Hdt : 0.0;
  if (m_nav.has_hdt) m_hdt_ms = DiagNowMs();

  // Which of these OpenCPN actually supplies is the first question when the
  // picture is in the wrong place, so log the transitions.
  const int now_flags = (m_nav.valid ? 1 : 0) | (m_nav.has_cog ? 2 : 0) |
                        (m_nav.has_hdt ? 4 : 0);
  if (now_flags != m_fix_flags) {
    m_fix_flags = now_flags;
    Log(2, wxString::Format(
               "OpenCPN fix: position %s, COG %s, heading %s (lat %.5f lon "
               "%.5f cog %.1f sog %.1f hdt %.1f)",
               m_nav.valid ? "yes" : "no", m_nav.has_cog ? "yes" : "no",
               m_nav.has_hdt ? "yes" : "no", m_nav.lat, m_nav.lon, m_nav.cog,
               m_nav.sog, m_nav.hdt));
  }
}

void mayara_pi::SetColorScheme(PI_ColorScheme cs) {
  m_color_scheme = cs;
  const MayaraTheme t = ThemeFor(cs, m_menu_font_pt);
  m_radar_intensity = t.radar_intensity;
  if (m_client) m_client->SetAllIntensity(t.radar_intensity);
  ApplyThemeToWindows();
}
