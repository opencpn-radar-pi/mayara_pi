int mayara_pi::Init() {
  m_parent_window = GetOCPNCanvasWindow();
  m_aui = GetFrameAuiManager();  // may be null in some builds
  LoadConfig();

  m_tool_id = InsertPlugInTool(
      _("Mayara"), &m_tool_bitmap, &m_tool_bitmap, wxITEM_CHECK,
      _("Mayara Radar"), _("Show or hide the Mayara radar PPI window"),
      nullptr, -1, 0, this);

  // Canvas right-click context menu. The overlay entry pops a menu of its own
  // rather than carrying a submenu: OpenCPN only began passing submenu clicks
  // back to plugins in September 2025, and before that they were silently
  // dropped -- an entry that does nothing is worse than one more click.
  {
    m_mi_overlay_item = new wxMenuItem(nullptr, wxID_ANY,
                                       _("Mayara radar overlay"),
                                       wxEmptyString, wxITEM_NORMAL);
    m_mi_overlay = AddCanvasContextMenuItem(m_mi_overlay_item, this);

    m_mi_menu_item = new wxMenuItem(nullptr, wxID_ANY, _("Mayara radar menu"),
                                    wxEmptyString, wxITEM_NORMAL);
    m_mi_menu = AddCanvasContextMenuItem(m_mi_menu_item, this);

    // Label says what the click will do, so it is never a guess.
    m_mi_ppi_item = new wxMenuItem(nullptr, wxID_ANY, _("Show Mayara PPI"),
                                   wxEmptyString, wxITEM_NORMAL);
    m_mi_ppi = AddCanvasContextMenuItem(m_mi_ppi_item, this);

    m_mi_ov_none = wxWindow::NewControlId();
    m_mi_ov_all = wxWindow::NewControlId();
    for (int k = 0; k < kMaxMenuRadars; ++k)
      m_mi_ov_radar[k] = wxWindow::NewControlId();
  }


  // Optional mayara-server of our own: start it before the client so it is
  // already listening on loopback by the time discovery runs.
  m_server = std::make_unique<MayaraServer>(this);
  m_server->LoadConfig();
  // Before m_client exists, so a config saved stale from before this fix
  // (Enabled() false, m_saved_server_url still the loopback address) is
  // cleaned up before it is ever read into the client as "remembered".
  ForgetLocalServerIfDisabled();
  if (m_server->Enabled()) m_server->Start();
  m_server->CheckLatest();  // silent when github.com is unreachable

  m_client = std::make_unique<MayaraClient>(MayaraExplicitUrl(),
                                            kMayaraServerFallback);
  if (!m_saved_server_url.empty())
    m_client->SetRememberedUrl(m_saved_server_url);  // fast reconnect
  if (!m_explicit_server_url.empty())
    m_client->SetServerUrl(m_explicit_server_url);   // Settings override wins
  SyncLocalServerUrl();
  m_client->SetHintUrl(OpenCpnSignalKUrl());
  m_client->SetClientId(m_client_id);
  if (!m_sk_token.empty())
    m_client->SetAuthToken(m_sk_token_server, m_sk_token);
  m_client->SetPalette(ActivePalette());  // before the first radar arrives
  LogSettings();
  m_client->Start();
  // An access request posted in an earlier session may still be waiting for
  // someone to approve it; pick it up where we left off.
  if (!m_sk_pending_href.empty())
    m_client->ResumeAccessRequest(m_sk_pending_server, m_sk_pending_href);

  // 1 Hz heartbeat: re-open windows persisted as shown once radars appear, and
  // keep a live geometry snapshot for saving (independent of a GPS fix).
  m_heartbeat = std::make_unique<CallbackTimer>([this]() {
    if (m_server) {
      m_server->Poll();  // weekly release check + notice a died-on-us server
      MaybeOfferServerUpdate();
    }
    SyncAccessConfig();
    if (m_windows_visible && m_windows.empty() && m_client &&
        m_client->RadarCount() > 0) {
      RebuildWindows();
      if (m_tool_id != -1) SetToolbarItemState(m_tool_id, true);
    }
    // Follow OpenCPN in/out of full screen.
    const bool fs = GetFullScreen();
    if (fs != m_ocpn_fullscreen) {
      m_ocpn_fullscreen = fs;
      SyncRadarFullScreen(fs);
    }
    // Snapshot geometry and shown/hidden state for persistence, but not while
    // full-screen (that would save the full-screen rects) or while the whole
    // group is off: every window reads as hidden then, which would capture
    // over each window's real individual state with a uniform "all hidden"
    // the moment the master toggle -- not the user closing one window --
    // is why they are all hidden right now.
    if (!m_ocpn_fullscreen && !m_windows.empty() && m_windows_visible)
      CaptureWindowState();

    if (m_client && m_diag.log_level > 0)
      for (const auto& line : m_client->TakeLog())
        Log(line.first, wxString::FromUTF8(line.second.c_str()));
    else if (m_client)
      m_client->TakeLog();  // keep the queue from filling while logging is off

    // Say when the answer to "where is the picture" changes, which is the
    // transition worth having in a log rather than the steady state.
    {
      double h = 0.0;
      wxString src;
      const bool have = ResolveHeading(-1, &h, &src);
      const wxString now = have ? src : wxString("none");
      if (now != m_last_heading_source) {
        Log(have ? 2 : 1,
            wxString::Format("heading source: %s -> %s",
                             m_last_heading_source.IsEmpty()
                                 ? wxString("(start)")
                                 : m_last_heading_source,
                             now));
        m_last_heading_source = now;
      }
    }

    PollGuardAlarms();
    FeedHeading();
    FeedTargets();
    SyncChartRange();
    SyncAutoRange();  // after it: the nested radar follows the outer one
    FitChartMenu();
    const int under = CanvasUnderMouse();
    if (under >= 0) m_menu_canvas = under;
    RefreshContextMenu(m_menu_canvas);

    // Remember the server that answered (fast reconnect next boot). Not gated
    // on a radar streaming: a server with nothing attached is still the right
    // address, and waiting for a radar meant a stale one that never answers
    // stayed first in line for every future session.
    if (m_client) {
      const std::string url = m_client->ConnectedUrl();
      if (!url.empty() && url != m_saved_server_url) {
        m_saved_server_url = url;
        SaveConfig();
      }
    }
    // When the radar can't be found, offer the search/manual-entry dialog --
    // or, once we know exactly which server we're talking to, point at its
    // own GUI instead (it has the brand-specific "why can't it find my
    // radar" guidance; we don't need to duplicate that here).
    if (m_client && m_client->Connected()) {
      m_no_radar_ticks = 0;
      m_no_radar_notice_dismissed = false;  // reset for the next time it goes quiet
      if (m_search_dialog) {
        m_search_dialog->Destroy();
        m_search_dialog = nullptr;
      }
    } else if (m_client) {
      ++m_no_radar_ticks;
      const std::string connected_url = m_client->ConnectedUrl();
      if (!connected_url.empty()) {
        // The radar API answered but listed nothing. This is the right
        // server either way (ours or a remote one) -- it just has no radar
        // to show, so the "where's the server" dialog below does not apply.
        if (m_no_radar_ticks >= 10 && !m_no_radar_notice_open &&
            !m_no_radar_notice_dismissed)
          ShowNoRadarNotice(connected_url, m_client->HelpUrl());
      } else {
        // The search dialog is for "we cannot find a server". When we are
        // running one ourselves we know exactly where it is, so silence about
        // a radar we have not found is the radar's problem, not the
        // locator's -- offering to go looking for a server would just be
        // wrong. If our own server is enabled but not running (the port was
        // taken, it crashed), the dialog is still the right thing to show.
        const bool own_server_up =
            m_server && m_server->Enabled() && m_server->Running();
        if (m_no_radar_ticks >= 10 && !own_server_up && !m_search_dialog &&
            !m_search_dismissed)
          ShowSearchDialog();
      }
    }
  });
  m_heartbeat->Start(1000);

  // Capabilities.
  //
  // WANTS_NMEA_EVENTS is what gets us SetPositionFixEx at all:
  // SendPositionFixToAllPlugIns() gates *both* the basic and the extended fix
  // on that flag, so without it OpenCPN never hands over position, COG, SOG or
  // heading -- the plugin was running entirely on what the radar stamps into
  // its own spokes.
  //
  // INSTALLS_CONTEXTMENU_ITEMS is what gets PrepareContextMenu called:
  // PrepareAllPluginContextMenus() skips any plugin without it. The menu items
  // themselves appear regardless, which is why this was invisible -- the menu
  // was there, it just never got the chance to update its labels.
  return WANTS_OPENGL_OVERLAY_CALLBACK | WANTS_OVERLAY_CALLBACK |
         WANTS_TOOLBAR_CALLBACK | INSTALLS_TOOLBAR_TOOL | WANTS_CURSOR_LATLON |
         WANTS_NMEA_EVENTS | INSTALLS_CONTEXTMENU_ITEMS | WANTS_PREFERENCES |
         USES_AUI_MANAGER;
}

bool mayara_pi::DeInit() {
  DestroyChartMenu();
  // Destroy the window first (synchronously) so its panels' timers stop calling
  // into the client before we free it.
  if (m_heartbeat) {
    m_heartbeat->Stop();
    m_heartbeat.reset();
  }
  if (m_search_dialog) {
    m_search_dialog->Destroy();
    m_search_dialog = nullptr;
  }
  if (m_access_dialog) {
    m_access_status = nullptr;
    m_access_button = nullptr;
    m_access_dialog->Destroy();
    m_access_dialog = nullptr;
  }
  SaveWindowState();  // remember visibility + positions before tearing down
  DestroyWindows(/*sync=*/true);
  if (m_tool_id != -1) {
    RemovePlugInTool(m_tool_id);
    m_tool_id = -1;
  }
  if (m_mi_overlay != -1) RemoveCanvasContextMenuItem(m_mi_overlay);
  if (m_mi_ppi != -1) RemoveCanvasContextMenuItem(m_mi_ppi);
  m_mi_overlay = m_mi_ppi = -1;
  if (m_client) {
    m_client->Stop();
    m_client.reset();
  }
  m_server.reset();  // stops the local mayara-server if we started one
  // Drain any pending (possibly cross-thread) log records now, while this
  // plugin's dylib -- and the string literals its log records point at -- is
  // still mapped. Otherwise OpenCPN flushes them on a later idle tick after
  // unloading us, dereferencing freed memory in OcpnLog::DoLogRecord.
  wxLog::FlushActive();
  return true;
}

