void mayara_pi::SyncChartRange() {
  if (!m_client) return;
  for (const auto& kv : m_canvas_radius_m) {
    const std::vector<int> radars = OverlayRadars(kv.first);
    if (radars.empty() || kv.second <= 0) continue;
    // Only the outer radar: a nested second one is steered by that one.
    const int idx = radars.front();
    // Per-radar: a detail radar overlaid on the chart can follow it while
    // another radar (kept at a fixed long range for weather, say) is left
    // alone even though it never appears on any canvas.
    if (!RangeAutoFor(m_client->RadarId(idx))) continue;
    RadarControls* c = m_client->ControlsAt(idx);
    if (!c) continue;
    std::vector<int> vals;
    for (const auto& d : c->Schema())
      if (d.id == "range") {
        vals = d.validValues;
        break;
      }
    if (vals.empty()) continue;
    int want = 0;
    for (int v : vals)
      if (v >= kv.second && (want == 0 || v < want)) want = v;
    if (want == 0)  // chart wider than the radar reaches: use its longest
      for (int v : vals) want = std::max(want, v);

    // Act only when this canvas's own desired value has changed, not on
    // every heartbeat tick. Comparing against the control's live value (as
    // this used to) raced two canvases sharing a radar: SetControlAt is
    // async, so neither canvas's check would see the other's just-sent value
    // yet, and both kept re-sending their own answer every tick -- the range
    // never settled. Tracking our own last ask, per canvas, breaks that: the
    // last canvas to actually change scale wins, and nothing repeats after.
    auto it = m_chart_range_last_want.find(kv.first);
    if (it != m_chart_range_last_want.end() && it->second == want) continue;
    m_chart_range_last_want[kv.first] = want;
    m_client->SetControlAt(idx, "range",
                           "{\"value\":" + std::to_string(want) + "}");
  }
}

void mayara_pi::ShowRadarMenu(int canvas) {
  const int was = m_chart_menu ? m_chart_menu_canvas : -1;
  DestroyChartMenu();
  if (was == canvas) return;  // second click on the same canvas: toggle off
  if (!m_client || m_client->RadarCount() == 0) return;

  wxWindow* cw = GetCanvasByIndex(canvas);
  if (!cw) cw = GetOCPNCanvasWindow();
  if (!cw) return;

  auto* p = new ControlsPanel(cw, m_client.get(), m_client->ActiveIndex());
  m_chart_menu = p;
  m_chart_menu_canvas = canvas;
  // Each fresh open starts from the auto-fit corner/size again.
  m_chart_menu_user_moved = false;
  m_chart_menu_user_sized = false;

  std::vector<int> all;
  for (int i = 0; i < m_client->RadarCount(); ++i) all.push_back(i);
  p->SetRadarList(all);
  p->ApplyTheme(ThemeFor(m_color_scheme, m_menu_font_pt));

  // Destroying a panel from inside its own button handler would unwind the
  // handler's own window, so let the event finish first.
  p->SetCloseCallback([this]() {
    if (m_parent_window)
      m_parent_window->CallAfter([this]() { DestroyChartMenu(); });
  });
  p->SetSettingsCallback([this]() { ShowSettings(m_parent_window); });
  p->SetViewControls([this]() { return OverlayOnAny(); },
                     [this](bool on) {
                       SetOverlayAll(on);
                       GetOCPNCanvasWindow()->Refresh(false);
                     },
                     [this]() { return AnyWindowShown(); },
                     [this](bool show) {
                       if (show) {
                         RaisePpiWindows();
                       } else {
                         m_windows_visible = false;
                         for (MayaraPpiWindow* w : m_windows)
                           if (w) w->ShowWindow(false);
                         SetToolbarItemState(m_tool_id, false);
                       }
                     });
  p->SetOrientationControl(
      [this, p]() { return OrientationFor(m_client->RadarId(p->RadarIndex())); },
      [this, p](int o) {
        SetOrientationFor(m_client->RadarId(p->RadarIndex()), o);
      });
  p->SetThresholdControl(
      [this, p]() { return ThresholdFor(m_client->RadarId(p->RadarIndex())); },
      [this, p](int l) {
        SetThresholdFor(m_client->RadarId(p->RadarIndex()), l);
      });
  p->SetRangeAutoControl(
      [this, p]() { return RadarInOverlay(p->RadarIndex()); },
      [this, p]() {
        return m_client && RangeAutoFor(m_client->RadarId(p->RadarIndex()));
      },
      [this, p](bool on) {
        if (m_client) SetRangeAutoFor(m_client->RadarId(p->RadarIndex()), on);
      });
  p->SetDockControl([this]() { return m_docked; },
                    [this](bool on) {
                      if (on == m_docked) return;
                      m_docked = on;
                      SaveConfig();
                      if (m_parent_window)
                        m_parent_window->CallAfter([this]() { RebuildWindows(); });
                    });
  p->SetPrefsControl([this]() { return m_prefs; },
                     [this](const PpiPrefs& q) {
                       m_prefs = q;
                       SaveConfig();
                       for (MayaraPpiWindow* w : m_windows)
                         if (w) w->ApplyPrefs();
                       GetOCPNCanvasWindow()->Refresh(false);
                     });
  // Guard zones can still be edited from here; there is no picture to drag
  // handles on, so this edit is the panel's own and is drawn on the chart.
  p->SetZoneEditHandlers(
      [this]() { return m_chart_zone; },
      [this](const ZoneEdit& z, bool commit) {
        m_chart_zone = z;
        if (commit && z.active && m_client) {
          char buf[256];
          std::snprintf(buf, sizeof(buf),
                        "{\"value\":%s,\"endValue\":%s,\"startDistance\":%s,"
                        "\"endDistance\":%s,\"enabled\":true}",
                        JsonNum(z.start_rad).c_str(), JsonNum(z.end_rad).c_str(),
                        JsonNum(z.start_m).c_str(), JsonNum(z.end_m).c_str());
          m_client->SetControlAt(z.radar_index, z.id, buf);
        }
        if (m_chart_menu) m_chart_menu->SyncNow();
        GetOCPNCanvasWindow()->Refresh(false);
      });

  // Draggable by its title bar, resizable via the corner grip -- otherwise
  // this is a fixed-size, fixed-position child of the chart canvas, not a
  // real window, so it has no title bar or resize border of its own.
  p->SetFreeFloatHandlers(
      [this](int dx, int dy) {
        if (!m_chart_menu) return;
        wxWindow* cw = m_chart_menu->GetParent();
        if (!cw) return;
        const wxSize cs = cw->GetClientSize();
        const wxSize sz = m_chart_menu->GetSize();
        wxPoint pos = m_chart_menu->GetPosition();
        pos.x = std::clamp(pos.x + dx, 0, std::max(0, cs.x - sz.x));
        pos.y = std::clamp(pos.y + dy, 0, std::max(0, cs.y - sz.y));
        m_chart_menu->SetPosition(pos);
        m_chart_menu_user_moved = true;
      },
      [this](int dw, int dh) {
        if (!m_chart_menu) return;
        wxWindow* cw = m_chart_menu->GetParent();
        if (!cw) return;
        const wxSize cs = cw->GetClientSize();
        const wxPoint pos = m_chart_menu->GetPosition();
        wxSize sz = m_chart_menu->GetSize();
        sz.x = std::clamp(sz.x + dw, 240, std::max(240, cs.x - pos.x));
        sz.y = std::clamp(sz.y + dh, 200, std::max(200, cs.y - pos.y));
        m_chart_menu->SetSize(sz);
        m_chart_menu->Layout();
        m_chart_menu->FitInside();
        m_chart_menu_user_sized = true;
      });

  // Top-left, clear of the chart bar along the bottom. Height is capped to the
  // canvas so a long control list scrolls rather than running off the chart --
  // and the scrollbar is kept permanently, both because a panel that can be
  // scrolled should say so, and because a bar that comes and goes reflows the
  // controls under the pointer.
  // The canvas owns its children, so a canvas that goes away (a layout change,
  // shutdown) takes the panel with it. Notice, rather than keep a dead pointer.
  p->Bind(wxEVT_DESTROY, [this](wxWindowDestroyEvent& e) {
    if (e.GetWindow() == m_chart_menu) {
      m_chart_menu = nullptr;
      m_chart_menu_canvas = -1;
    }
    e.Skip();
  });
  FitChartMenu();
#ifdef __WXMSW__
  // wxMSW never sets WS_CLIPSIBLINGS -- see wxWidgets src/msw/window.cpp, which
  // states overlapping windows are officially unsupported. This panel is a
  // sibling of glChartCanvas (a child of ChartCanvas, like us), and the GL
  // canvas repaints the whole chart continuously, so without the style it paints
  // straight over the panel: it draws once, is erased, and only the widgets that
  // refresh themselves reappear. Give every sibling the style, this panel too.
  for (wxWindow* sib : cw->GetChildren()) {
    if (!sib || !sib->GetHandle()) continue;
    HWND h = static_cast<HWND>(sib->GetHandle());
    ::SetWindowLong(h, GWL_STYLE,
                    ::GetWindowLong(h, GWL_STYLE) | WS_CLIPSIBLINGS);
  }
#endif
  p->Show();
  p->Raise();
}

// The panel builds itself from the schema on its own timer, so at this point
// it holds a "waiting for radar" placeholder and knows nothing about how wide
// it wants to be. Size it to the canvas now and keep following it: full height,
// because a control list is always longer than the room for it, and the wider
// of its own idea and a readable minimum. Once the user has dragged or resized
// it by hand (SetFreeFloatHandlers), that axis is theirs until the menu is
// next reopened -- this only re-clamps it back onto a canvas that shrank.
void mayara_pi::FitChartMenu() {
  if (!m_chart_menu) return;
  wxWindow* cw = m_chart_menu->GetParent();
  if (!cw) return;
  const wxSize cs = cw->GetClientSize();

  int w, h;
  if (m_chart_menu_user_sized) {
    const wxSize cur = m_chart_menu->GetSize();
    w = cur.x;
    h = cur.y;
  } else {
    const wxSize best = m_chart_menu->GetEffectiveMinSize();  // gutter included
    int want_w = std::max(320, best.x);
#ifdef __WXMSW__
    // Room for the native vertical scrollbar, outside the client area.
    want_w += wxSystemSettings::GetMetric(wxSYS_VSCROLL_X, m_chart_menu);
#endif
    w = want_w;
    // As tall as it needs, never taller than the chart: a panel sized to the
    // canvas is mostly empty, and one sized to a placeholder scrolls
    // everything real off the bottom.
    h = std::max(240, best.y);
  }
  w = std::min(w, std::max(240, cs.x - 2 * kChartMenuMargin));
  h = std::min(h, std::max(200, cs.y - 2 * kChartMenuMargin));

  int x, y;
  if (m_chart_menu_user_moved) {
    const wxPoint cur = m_chart_menu->GetPosition();
    x = cur.x;
    y = cur.y;
  } else {
    x = kChartMenuMargin;
    y = kChartMenuMargin;
  }
  x = std::clamp(x, 0, std::max(0, cs.x - w));
  y = std::clamp(y, 0, std::max(0, cs.y - h));

  if (m_chart_menu->GetSize() == wxSize(w, h) &&
      m_chart_menu->GetPosition() == wxPoint(x, y))
    return;
  m_chart_menu->SetSize(x, y, w, h);
  m_chart_menu->Layout();
  m_chart_menu->FitInside();  // virtual size from the content: the bar's range
}

void mayara_pi::DestroyChartMenu() {
  if (!m_chart_menu) return;
  ControlsPanel* p = m_chart_menu;  // clear first: Destroy() is deferred
  m_chart_menu = nullptr;
  m_chart_menu_canvas = -1;
  p->Destroy();
}

void mayara_pi::RaisePpiWindows() {
  if (m_windows.empty()) RebuildWindows();
  m_windows_visible = true;
  // Each window's own last shown/hidden state, when available -- a blanket
  // show would bring back a window the user closed on its own along with
  // the rest of the group. But this is an explicit "show the PPI" action:
  // if every window individually saved as hidden, honouring that literally
  // would show nothing at all and leave the very button that asked for this
  // with nothing left to do next time either -- fall back to showing
  // everything rather than restore into a dead end.
  if (!RestoreWindowShown() || !AnyWindowShown())
    for (MayaraPpiWindow* win : m_windows)
      if (win) win->ShowWindow(true);
  for (MayaraPpiWindow* win : m_windows)
    if (win && win->IsWindowShown()) {
      if (wxFrame* f = win->HostFrame()) f->Raise();
    }
  SetToolbarItemState(m_tool_id, true);
}

